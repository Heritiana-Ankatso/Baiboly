#!/usr/bin/env python3
"""Builds the app icon's vector drawables and docs/logo.svg from the logo's geometry.

The logo (an open book whose pages leave a cross between them) draws the cross with an SVG mask, which Android
vector drawables do not have; here the cross is cut out of the page shapes as real geometry (shapely), so the
result is the same picture and the one-colour themed icon keeps the cross as a gap.

    pip install shapely && python3 tools/make_icon.py
"""
import math
import pathlib
from shapely.geometry import LineString, MultiPolygon, Polygon, box
from shapely.ops import unary_union

ROOT = pathlib.Path(__file__).resolve().parent.parent
RES = ROOT / "app/src/main/res"

# colours: the logo's own, and the three its file left unfilled (circle, page edge, page lines)
NAVY, BACK, CREAM = "#1B2F5B", "#aca9a0", "#F6F1E4"
EDGE, LINES = "#DCD6C6", "#aca9a0"

def cubic(p0, p1, p2, p3, n=36):
    return [tuple((1 - t) ** 3 * a + 3 * (1 - t) ** 2 * t * b + 3 * (1 - t) * t ** 2 * c + t ** 3 * d
                  for a, b, c, d in zip(p0, p1, p2, p3)) for t in (i / n for i in range(n + 1))]

def build(segs):
    """segs: ('M',p) ('L',p) ('C',p1,p2,p3) in order; returns the flattened points."""
    pts, cur = [], None
    for s in segs:
        if s[0] in "ML":
            cur = s[1]; pts.append(cur)
        else:
            pts += cubic(cur, s[1], s[2], s[3])[1:]; cur = s[3]
    return pts

# one half of the book (the left one), in the logo's own coordinates
P1 = build([("M", (120, 72)), ("C", (98, 55.8), (83, 43.8), (45, 48)), ("L", (16, 117)), ("L", (16, 132.63)),
            ("C", (56.56, 127.03), (94, 129.82), (120, 147.25))])
P2 = build([("M", (16, 113)), ("C", (53.44, 107.4), (92.96, 110.2), (120, 125)), ("L", (120, 142)),
            ("C", (92.96, 127.2), (53.44, 124.4), (16, 130))])
L1 = build([("M", (16, 118.67)), ("C", (53.44, 113.07), (92.96, 115.87), (120, 130.67))])
L2 = build([("M", (16, 124.33)), ("C", (53.44, 118.73), (92.96, 121.53), (120, 136.33))])
P4 = build([("M", (120, 60)), ("C", (100, 50.2), (77, 40.4), (45, 46)), ("L", (16, 113)),
            ("C", (53.44, 107.4), (92.96, 110.2), (120, 125))])

CROSS = unary_union([box(111.5, 20, 128.5, 190), box(83, 75, 157, 92)])

def mirror(g):
    return Polygon([(240 - x, y) for x, y in g.exterior.coords]) if isinstance(g, Polygon) else \
        MultiPolygon([mirror(p) for p in g.geoms])

def layer(points, line=False):
    g = LineString(points).buffer(0.8, cap_style=2) if line else Polygon(points).buffer(0)
    left = g.difference(CROSS)
    return unary_union([left, mirror(left)] if not left.is_empty else [])

# back to front, as the logo draws them: page edge, thickness, page lines, page top
LAYERS = [(BACK, layer(P1)), (EDGE, layer(P2)), (LINES, layer(L1, True)), (LINES, layer(L2, True)), (CREAM, layer(P4))]
SILHOUETTE = unary_union([g for _, g in LAYERS])

def polys(g):
    return list(g.geoms) if isinstance(g, MultiPolygon) else ([] if g.is_empty else [g])

def path_data(g, f):
    out = []
    for p in polys(g):
        for ring in [p.exterior, *p.interiors]:
            c = list(ring.coords)[:-1]
            out.append("M" + " L".join(f"{f(x, y)[0]:.2f},{f(x, y)[1]:.2f}" for x, y in c) + "Z")
    return " ".join(out)

def fit(size, radius, centre=None):
    """Maps the logo's coordinates (book group applied) into a [size]x[size] viewport, the book within [radius] of the centre."""
    place = lambda x, y: (36.4 + 0.78 * x, 51.22 + 0.78 * y)
    far = max(math.dist(place(x, y), (130, 130)) for p in polys(SILHOUETTE) for x, y in p.exterior.coords)
    k = radius / far
    c = size / 2
    return lambda x, y: (c + k * (place(x, y)[0] - 130), c + k * (place(x, y)[1] - 130))

def vector(size_dp, view, body, comment):
    return (f'<?xml version="1.0" encoding="utf-8"?>\n<!-- {comment} -->\n'
            f'<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            f'    android:width="{size_dp}dp" android:height="{size_dp}dp" android:viewportWidth="{view}" android:viewportHeight="{view}">\n'
            f'{body}</vector>\n')

def paths(f, colour=None, groups=None):
    return "".join(f'    <path android:fillColor="{colour or c}"\n        android:pathData="{path_data(g, f)}" />\n'
                   for c, g in (groups if groups is not None else LAYERS))

# launcher: the book inside the adaptive icon's safe circle (radius 33 of 108)
f = fit(108, 30.5)
(RES / "drawable/ic_launcher_foreground.xml").write_text(vector(108, 108, paths(f),
    "The open Bible logo: two pages that leave a cross between them. Generated by tools/make_icon.py."))
(RES / "drawable/ic_launcher_monochrome.xml").write_text(vector(108, 108, paths(f, "#FF000000", [(None, SILHOUETTE)]),
    "Themed (monochrome) launcher icon: the same book and cross. Generated by tools/make_icon.py."))
f24 = fit(24, 11.6)
(RES / "drawable/ic_stat_read.xml").write_text(vector(24, 24, paths(f24, "#FFFFFFFF", [(None, SILHOUETTE)]),
    "Status-bar icon while reading aloud: the app's open book with its cross. Generated by tools/make_icon.py."))

# the logo as a file, with its three unfilled colours given
svg = f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 260 260" width="512" height="512" role="img" aria-label="Open Bible logo"><title>Open Bible logo</title><circle cx="130" cy="130" r="126" fill="{NAVY}"/><g transform="translate(36.4 51.22) scale(0.78)"><mask id="cut" maskUnits="userSpaceOnUse" x="-60" y="-40" width="360" height="280"><rect x="-60" y="-40" width="360" height="280" fill="#fff"/><rect x="111.5" y="20" width="17" height="170" fill="#000"/><rect x="83" y="75" width="74" height="17" fill="#000"/></mask><g mask="url(#cut)">'''
half = f'''<path d="M120 72 C98 55.8 83 43.8 45 48 L16 117 L16 132.63 C56.56 127.03 94 129.82 120 147.25 Z" fill="{BACK}"/><path d="M16 113 C53.44 107.4 92.96 110.2 120 125 L120 142 C92.96 127.2 53.44 124.4 16 130 Z" fill="{EDGE}"/><path d="M16 118.67 C53.44 113.07 92.96 115.87 120 130.67 M16 124.33 C53.44 118.73 92.96 121.53 120 136.33 " fill="none" stroke="{LINES}" stroke-width="1.6"/><path d="M120 60 C100 50.2 77 40.4 45 46 L16 113 C53.44 107.4 92.96 110.2 120 125 Z" fill="{CREAM}"/>'''
svg += half + f'<g transform="translate(240 0) scale(-1 1)">{half}</g></g></g></svg>\n'
(ROOT / "docs/logo.svg").write_text(svg)
print("ok", [len(path_data(g, f)) for _, g in LAYERS])
